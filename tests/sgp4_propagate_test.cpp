core::Sgp4Model Init(const Case& c) {
    const auto tle = core::ParseTle(std::string(c.line1) + "\n" + c.line2 + "\n");
    EXPECT_TRUE(tle.has_value()) << c.name;
    const auto model = core::InitSgp4(tle.value_or(core::Tle{}));
    EXPECT_TRUE(model.has_value()) << c.name;
    return model.value_or(core::Sgp4Model{});
}

double Norm(const core::Vec3& v) {
    return std::sqrt(v.x * v.x + v.y * v.y + v.z * v.z);
}

TEST(Propagate, MatchesPythonSgp4) {
    constexpr double kPositionToleranceKm = 1e-6; // one millimetre
    constexpr double kVelocityToleranceKmPerSec = 1e-9;
    for (const Case& c : Cases()) {
        const core::Sgp4Model model = Init(c);
        for (const Row& row : c.rows) {
            SCOPED_TRACE(std::string(c.name) + " t=" + std::to_string(row[0]));
            const auto state = core::Propagate(model, row[0]);
            ASSERT_TRUE(state.has_value());
            EXPECT_NEAR(state->position.x, row[1], kPositionToleranceKm);
            EXPECT_NEAR(state->position.y, row[2], kPositionToleranceKm);
            EXPECT_NEAR(state->position.z, row[3], kPositionToleranceKm);
            EXPECT_NEAR(state->velocity.x, row[4], kVelocityToleranceKmPerSec);
            EXPECT_NEAR(state->velocity.y, row[5], kVelocityToleranceKmPerSec);
            EXPECT_NEAR(state->velocity.z, row[6], kVelocityToleranceKmPerSec);
        }
    }
}

// Vallado's published verification output for satellite 00005 (Spacetrack Report #3 test case,
// from the SGP4-VER results in "Revisiting Spacetrack Report #3"). Independent of python-sgp4.
TEST(Propagate, MatchesValladosPublishedVerificationVectors) {
    const Case& sat00005 = Cases()[1];
    ASSERT_STREQ(sat00005.name, "sat00005");
    const core::Sgp4Model model = Init(sat00005);

    const auto atEpoch = core::Propagate(model, 0.0);
    ASSERT_TRUE(atEpoch.has_value());
    EXPECT_NEAR(atEpoch->position.x, 7022.46529266, 1e-6);
    EXPECT_NEAR(atEpoch->position.y, -1400.08296755, 1e-6);
    EXPECT_NEAR(atEpoch->position.z, 0.03995155, 1e-6);
    EXPECT_NEAR(atEpoch->velocity.x, 1.893841015, 1e-8);
    EXPECT_NEAR(atEpoch->velocity.y, 6.405893759, 1e-8);
    EXPECT_NEAR(atEpoch->velocity.z, 4.534807250, 1e-8);

    const auto after6h = core::Propagate(model, 360.0);
    ASSERT_TRUE(after6h.has_value());
    EXPECT_NEAR(after6h->position.x, -7154.03120202, 1e-6);
    EXPECT_NEAR(after6h->position.y, -3783.17682504, 1e-6);
    EXPECT_NEAR(after6h->position.z, -3536.19412294, 1e-6);
    EXPECT_NEAR(after6h->velocity.x, 4.741887409, 1e-8);
    EXPECT_NEAR(after6h->velocity.y, -4.151817765, 1e-8);
    EXPECT_NEAR(after6h->velocity.z, -2.093935425, 1e-8);
}

TEST(Propagate, StateIsPhysicallyConsistentForTheIss) {
    const core::Sgp4Model model = Init(Cases()[0]);
    for (double t = 0.0; t <= 1440.0; t += 15.0) {
        const auto state = core::Propagate(model, t);
        ASSERT_TRUE(state.has_value()) << "t=" << t;

        // The ISS stays 400-430 km above the surface and moves at about 7.66 km/s.
        const double altitudeKm = Norm(state->position) - 6378.135;
        EXPECT_GT(altitudeKm, 380.0) << "t=" << t;
        EXPECT_LT(altitudeKm, 450.0) << "t=" << t;
        EXPECT_NEAR(Norm(state->velocity), 7.66, 0.1) << "t=" << t;

        // Velocity is nearly perpendicular to the radius for a near-circular orbit.
        const double cosine =
            (state->position.x * state->velocity.x + state->position.y * state->velocity.y +
             state->position.z * state->velocity.z) /
            (Norm(state->position) * Norm(state->velocity));
        EXPECT_NEAR(cosine, 0.0, 0.01) << "t=" << t;
    }
}

TEST(Propagate, ReturnsToTheSamePointAfterOneOrbitalPeriod) {
    // The ISS period is 1440 / 15.49188396 = 92.95 minutes. After one period the satellite is
    // close to where it started (drift from J2 and drag is a few km).
    const core::Sgp4Model model = Init(Cases()[0]);
    const auto start = core::Propagate(model, 0.0);
    const auto later = core::Propagate(model, 1440.0 / 15.49188396);
    ASSERT_TRUE(start.has_value());
    ASSERT_TRUE(later.has_value());
    const core::Vec3 diff{later->position.x - start->position.x,
                          later->position.y - start->position.y,
                          later->position.z - start->position.z};
    EXPECT_LT(Norm(diff), 60.0);
}

TEST(Propagate, ReportsFailureWhenDragDestroysTheOrbit) {
    // python-sgp4 reports error 1 (mean eccentricity out of range) at these times.
    struct Failure {
        std::size_t caseIndex;
        double minutes;
    };
    const std::vector<Failure> failures = {
        {2, 10080.0}, {3, 360.0}, {3, 720.0}, {3, 1440.0}, {3, 10080.0},
    };
    for (const Failure& f : failures) {
        const Case& c = Cases()[f.caseIndex];
        EXPECT_FALSE(core::Propagate(Init(c), f.minutes).has_value())
            << c.name << " t=" << f.minutes;
    }
}

TEST(Propagate, ReportsFailureForASatelliteBelowTheSurface) {
    // Force a semi-major axis under one Earth radius, which the reference treats as decayed.
    core::Sgp4Model model = Init(Cases()[0]);
    model.meanMotion = 0.09;
    EXPECT_FALSE(core::Propagate(model, 0.0).has_value());
}

