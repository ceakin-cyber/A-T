// Cases where python-sgp4 reports error 1 (mean eccentricity out of range) because drag has
// pulled the orbit down: {case index, minutes since epoch}.
const std::vector<std::pair<int, double>>& DecayedCases() {
    static const std::vector<std::pair<int, double>> cases = {
        {2, 10080.0},
        {3, 720.0},
        {3, 1440.0},
        {3, 10080.0},
    };
    return cases;
}

core::Sgp4Model Init(const Case& c) {
    const auto tle = core::ParseTle(std::string(c.line1) + "\n" + c.line2 + "\n");
    EXPECT_TRUE(tle.has_value()) << c.name;
    const auto model = core::InitSgp4(tle.value_or(core::Tle{}));
    EXPECT_TRUE(model.has_value()) << c.name;
    return model.value_or(core::Sgp4Model{});
}

// Relative comparison, with a tiny absolute floor for coefficients that are exactly zero.
void ExpectClose(double actual, double expected, const char* what) {
    const double tolerance = 1e-10 * std::fabs(expected) + 1e-30;
    EXPECT_NEAR(actual, expected, tolerance) << what;
}

// Angles are compared modulo 2*pi, since the reference keeps the node's sign for negative times.
void ExpectSameAngle(double actual, double expected, const char* what) {
    double difference = std::fmod(actual - expected, kTwoPi);
    if (difference > std::numbers::pi) {
        difference -= kTwoPi;
    } else if (difference < -std::numbers::pi) {
        difference += kTwoPi;
    }
    EXPECT_NEAR(difference, 0.0, 1e-9) << what;
}

TEST(SecularCoefficients, MatchPythonSgp4) {
    for (const Case& c : Cases()) {
        SCOPED_TRACE(c.name);
        const core::Sgp4Model m = Init(c);
        const Coefficients actual = {m.cc1,    m.cc4,   m.cc5,    m.mdot,  m.argpdot, m.nodedot,
                                     m.omgcof, m.xmcof, m.nodecf, m.t2cof, m.delmo,   m.sinmao,
                                     m.d2,     m.d3,    m.d4,     m.t3cof, m.t4cof,   m.t5cof};
        static const char* const names[] = {
            "cc1",   "cc4",   "cc5",    "mdot", "argpdot", "nodedot", "omgcof", "xmcof", "nodecf",
            "t2cof", "delmo", "sinmao", "d2",   "d3",      "d4",      "t3cof",  "t4cof", "t5cof"};
        for (std::size_t i = 0; i < actual.size(); ++i) {
            ExpectClose(actual[i], c.coefficients[i], names[i]);
        }
    }
}

TEST(SecularCoefficients, SimpleOrbitsHaveNoHigherOrderDragTerms) {
    for (const Case& c : Cases()) {
        const core::Sgp4Model m = Init(c);
        if (m.isSimple) {
            EXPECT_EQ(m.d2, 0.0) << c.name;
            EXPECT_EQ(m.t5cof, 0.0) << c.name;
        } else {
            EXPECT_NE(m.d2, 0.0) << c.name;
        }
    }
}

TEST(PropagateSecular, MatchesPythonSgp4MeanElements) {
    for (const Case& c : Cases()) {
        const core::Sgp4Model m = Init(c);
        for (const Row& row : c.rows) {
            SCOPED_TRACE(std::string(c.name) + " t=" + std::to_string(row[0]));
            const auto e = core::PropagateSecular(m, row[0]);
            ASSERT_TRUE(e.has_value());
            ExpectClose(e->semiMajorAxis, row[1], "am");
            ExpectClose(e->eccentricity, row[2], "em");
            ExpectClose(e->inclination, row[3], "im");
            ExpectSameAngle(e->raan, row[4], "Om");
            ExpectSameAngle(e->argPerigee, row[5], "om");
            ExpectSameAngle(e->meanAnomaly, row[6], "mm");
            ExpectClose(e->meanMotion, row[7], "nm");
        }
    }
}

TEST(PropagateSecular, AnglesAreWrappedIntoZeroToTwoPi) {
    for (const Case& c : Cases()) {
        const core::Sgp4Model m = Init(c);
        for (const Row& row : c.rows) {
            const auto e = core::PropagateSecular(m, row[0]);
            ASSERT_TRUE(e.has_value());
            for (const double angle : {e->raan, e->argPerigee, e->meanAnomaly}) {
                EXPECT_GE(angle, 0.0) << c.name;
                EXPECT_LT(angle, kTwoPi) << c.name;
            }
        }
    }
}

TEST(PropagateSecular, AtEpochReturnsTheInitialElements) {
    const Case& iss = Cases()[0];
    const core::Sgp4Model m = Init(iss);
    const auto e = core::PropagateSecular(m, 0.0);
    ASSERT_TRUE(e.has_value());
    ExpectClose(e->eccentricity, m.eccentricity, "eccentricity");
    ExpectSameAngle(e->raan, m.raan, "raan");
    ExpectSameAngle(e->argPerigee, m.argPerigee, "argPerigee");
    ExpectSameAngle(e->meanAnomaly, m.meanAnomaly, "meanAnomaly");
}

TEST(PropagateSecular, ReportsFailureWhenDragDestroysTheOrbit) {
    for (const auto& [index, minutes] : DecayedCases()) {
        const Case& c = Cases()[static_cast<std::size_t>(index)];
        const core::Sgp4Model m = Init(c);
        EXPECT_FALSE(core::PropagateSecular(m, minutes).has_value()) << c.name << " t=" << minutes;
    }
}

TEST(PropagateSecular, RejectsAModelWithNoMeanMotion) {
    core::Sgp4Model m = Init(Cases()[0]);
    m.meanMotion = 0.0;
    EXPECT_FALSE(core::PropagateSecular(m, 10.0).has_value());
}

